// binary heap: before(a, b) is true when a should come out first
class Heap {
  constructor(before) {
    this.before = before;
    this.items = [];
  }

  get size() {
    return this.items.length;
  }

  peek() {
    return this.items[0];
  }

  push(value) {
    const a = this.items;
    a.push(value);
    // sift up: swap with the parent while the new item should come out sooner
    let i = a.length - 1;
    while (i > 0) {
      const parent = (i - 1) >> 1;
      if (!this.before(a[i], a[parent])) break;
      [a[i], a[parent]] = [a[parent], a[i]];
      i = parent;
    }
  }

  pop() {
    const a = this.items;
    const top = a[0];
    const last = a.pop();
    if (a.length) {
      a[0] = last;
      // sift down: swap with whichever child should come out first
      let i = 0;
      while (true) {
        const l = 2 * i + 1;
        const r = l + 1;
        let first = i;
        if (l < a.length && this.before(a[l], a[first])) first = l;
        if (r < a.length && this.before(a[r], a[first])) first = r;
        if (first === i) break;
        [a[i], a[first]] = [a[first], a[i]];
        i = first;
      }
    }
    return top;
  }
}

export default class MedianFinder {
  constructor() {
    this.low = new Heap((a, b) => a > b); // max-heap: the smaller half
    this.high = new Heap((a, b) => a < b); // min-heap: the larger half
  }

  /** @param {number} num */
  addNum(num) {
    // route through low so the biggest of the small half moves up into high
    this.low.push(num);
    this.high.push(this.low.pop());
    // keep low the same size as high, or one bigger
    if (this.high.size > this.low.size) this.low.push(this.high.pop());
  }

  /** @return {number} */
  findMedian() {
    // odd count: the extra item is low's top
    if (this.low.size > this.high.size) return this.low.peek();
    return (this.low.peek() + this.high.peek()) / 2;
  }
}
